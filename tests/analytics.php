<?php
declare(strict_types=1);
require dirname(__DIR__).'/app/bootstrap.php';
ini_set('display_errors','1');
error_reporting(E_ALL);
require dirname(__DIR__).'/app/models/analytics.php';
$db=db_connect(atlas_config());
require dirname(__DIR__).'/app/controllers/analytics.php';
$date=(new DateTimeImmutable('today'))->format('Y-m-d');
$from=(new DateTimeImmutable('today'))->modify('-7 days')->format('Y-m-d');
$to=(new DateTimeImmutable('today'))->modify('+30 days')->format('Y-m-d');
$confirmed=analytics_report($db,['tipo'=>'reservas','inicio'=>$from,'fim'=>$date,'status'=>'confirmada']);
if(count($confirmed)!==3) throw new RuntimeException('Filtro por período/situação encontrou '.count($confirmed).' reservas recentes em vez de três.');
$paid=analytics_report($db,['tipo'=>'receita','inicio'=>$from,'fim'=>$date]);
if(count($paid)!==2 || array_sum(array_map(static fn($r)=>money_cents((string)$r['total']),$paid))!==445000) throw new RuntimeException('Receita por data de pagamento incorreta.');
$pending=analytics_report($db,['tipo'=>'pendentes','inicio'=>$from,'fim'=>$date]);
if(count($pending)!==2 || money_cents((string)$pending[1]['saldo'])!==200000) throw new RuntimeException('Saldo pendente incorreto.');
$history=analytics_report($db,['tipo'=>'cliente','cliente'=>1]);
if(count($history)!==1) throw new RuntimeException('Histórico por cliente incorreto.');
$occupancy=analytics_report($db,['tipo'=>'ocupacao','inicio'=>$date,'fim'=>$to]);
if(count($occupancy)!==3) throw new RuntimeException('Filtro por data de partida incorreto.');
$bonito=$occupancy[2];
if($bonito['pacote']!=='Águas de Bonito' || (int)$bonito['quantidade']!==5 || (int)$bonito['capacidade']!==8 || (string)$bonito['ocupacao']!=='62.5') throw new RuntimeException('Ocupação de Bonito incorreta.');
$popular=analytics_report($db,['tipo'=>'populares','inicio'=>$from,'fim'=>$date]);
if(!$popular || $popular[0]['pacote']!=='Águas de Bonito' || (int)$popular[0]['quantidade']!==2) throw new RuntimeException('Ranking de pacotes incorreto.');
$destinations=analytics_report($db,['tipo'=>'destinos','inicio'=>$from,'fim'=>$date]);
if(!str_starts_with($destinations[0]['destino'],'Bonito') || (int)$destinations[0]['passageiros']!==5) throw new RuntimeException('Ranking de destinos incorreto.');
$summary=analytics_report_summary($db,['tipo'=>'receita','inicio'=>$from,'fim'=>$date]);
if((int)$summary['registros']!==2 || money_cents((string)$summary['valor'])!==445000) throw new RuntimeException('Resumo do relatório de receita incorreto.');
$page=analytics_report($db,['tipo'=>'receita','inicio'=>$from,'fim'=>$date],1,1);
if(count($page)!==1 || money_cents((string)$page[0]['total'])!==187000) throw new RuntimeException('Paginação do relatório de receita incorreta.');
$dashboard=analytics_dashboard($db);
if((int)$dashboard['clientes']!==5 || (int)$dashboard['reservas']!==4 || (int)$dashboard['ocupacao']!==30 || !$dashboard['alertas']) throw new RuntimeException('KPIs ou alertas do painel incorretos: '.json_encode(array_intersect_key($dashboard,array_flip(['clientes','reservas','ocupacao','alertas']))));
foreach(['=1+1',' +SUM(A1:A2)','@cmd',"\t-1"] as $value) if(!str_starts_with(analytics_csv_safe($value),"'")) throw new RuntimeException('CSV formula injection not escaped');
if(analytics_csv_safe('Turismo')!=='Turismo') throw new RuntimeException('CSV altered ordinary text');
echo "Relatórios, filtros, KPIs e sanitização CSV passaram com dados de seed.\n";
